import "server-only";
import { z } from "zod";
function previewOrigin() {
  if (process.env.VERCEL !== "1" || process.env.VERCEL_ENV !== "preview")
    return undefined;
  const host = process.env.VERCEL_URL;
  if (!host || !/^[a-z0-9]+(?:-[a-z0-9]+)*\.vercel\.app$/.test(host))
    return undefined;
  return `https://${host}`;
}
const schema = z.object({
  DATABASE_URL: z
    .url()
    .refine((v) => /^postgres(ql)?:/.test(v), "Use a PostgreSQL URL"),
  NEXTAUTH_URL: z.url().refine((value) => {
    try {
      const url = new URL(value);
      return (
        ["http:", "https:"].includes(url.protocol) &&
        !url.username &&
        !url.password &&
        url.pathname === "/" &&
        !url.search &&
        !url.hash
      );
    } catch {
      return false;
    }
  }),
  NEXTAUTH_SECRET: z.string().min(32),
});
export function getEnv() {
  const result = schema.safeParse({
    DATABASE_URL: process.env.DATABASE_URL,
    // Preview URLs are generated by Vercel. Never derive the origin from user input.
    // NextAuth v4 also supports Vercel origins when NEXTAUTH_URL is absent.
    NEXTAUTH_URL: process.env.NEXTAUTH_URL ?? previewOrigin(),
    NEXTAUTH_SECRET: process.env.NEXTAUTH_SECRET,
  });
  if (!result.success) {
    // Log variable names only: Zod issues and environment values can contain secrets.
    console.error(
      "Server configuration missing or invalid:",
      [...new Set(result.error.issues.map((issue) => issue.path[0]))].join(
        ", ",
      ),
    );
    throw new Error("Server environment is incomplete. See .env.example.");
  }
  if (
    process.env.NODE_ENV === "production" &&
    !result.data.NEXTAUTH_URL.startsWith("https://")
  )
    throw new Error("Production requires HTTPS.");
  const preview = previewOrigin();
  if (preview && new URL(result.data.NEXTAUTH_URL).origin !== preview) {
    console.error(
      "Server configuration missing or invalid:",
      "NEXTAUTH_URL (Preview origin mismatch)",
    );
    throw new Error("Server environment is incomplete. See .env.example.");
  }
  return {
    ...result.data,
    NEXTAUTH_URL: new URL(result.data.NEXTAUTH_URL).origin,
  };
}
